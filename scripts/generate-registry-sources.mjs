/**
 * Embeds raw Vue SFC source into a JS module at build time.
 *
 * Runtime filesystem / Nitro serverAssets lookups are empty on Vercel
 * serverless (dynamic getItem is not file-traced into the function bundle).
 * A static JS module import is compiled into the server bundle, so source
 * cannot vanish after deploy.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const uiDir = path.join(rootDir, 'app', 'components', 'ui')
const outDir = path.join(rootDir, 'server', 'utils')
const outFile = path.join(outDir, 'registry-sources.generated.mjs')

function writeAtomic(filePath, contents) {
  const tmpPath = `${filePath}.${process.pid}.tmp`
  fs.writeFileSync(tmpPath, contents, 'utf8')
  fs.copyFileSync(tmpPath, filePath)
  fs.unlinkSync(tmpPath)
}

export function generateRegistrySources() {
  if (!fs.existsSync(uiDir)) {
    throw new Error(`[registry-sources] UI directory not found: ${uiDir}`)
  }

  const files = fs.readdirSync(uiDir).filter(name => name.endsWith('.vue'))
  if (files.length === 0) {
    throw new Error(`[registry-sources] No .vue files found in ${uiDir}`)
  }

  /** @type {Record<string, string>} */
  const sources = {}
  for (const fileName of files) {
    const content = fs.readFileSync(path.join(uiDir, fileName), 'utf8')
    if (!content.trim()) {
      throw new Error(`[registry-sources] Refusing to embed empty source: ${fileName}`)
    }
    sources[fileName] = content
  }

  fs.mkdirSync(outDir, { recursive: true })
  const encoded = Buffer.from(JSON.stringify(sources), 'utf8').toString('base64')
  const moduleSource = `// Generated by scripts/generate-registry-sources.mjs. Do not edit.
const encoded = ${JSON.stringify(encoded)}
function decodeRegistrySources(value) {
  return JSON.parse(Buffer.from(value, 'base64').toString('utf8'))
}
export const registrySources = decodeRegistrySources(encoded)
export default registrySources
`
  writeAtomic(outFile, moduleSource)
  return { outFile, files: Object.keys(sources), sources }
}

const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isDirectRun) {
  const result = generateRegistrySources()
  console.log(`[registry-sources] Wrote ${result.files.length} components to ${result.outFile}`)
}
